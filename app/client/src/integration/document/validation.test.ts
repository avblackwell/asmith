import { exampleDashboardDocument } from "./exampleDashboardDocument";
import {
  DashboardDocumentValidationError,
  importDashboardDocumentJson,
  parseDashboardDocument,
  serializeDashboardDocument,
} from "./validation";

// The mutable copy intentionally permits malformed values in negative tests.
// eslint-disable-next-line @typescript-eslint/no-explicit-any
function copyFixture(): Record<string, any> {
  return JSON.parse(JSON.stringify(exampleDashboardDocument));
}

describe("dashboard document V1", () => {
  it("validates and round-trips a realistic Appsmith layout", () => {
    expect(parseDashboardDocument(exampleDashboardDocument)).toBe(
      exampleDashboardDocument,
    );
    expect(
      importDashboardDocumentJson(
        serializeDashboardDocument(exampleDashboardDocument),
      ),
    ).toEqual(exampleDashboardDocument);
  });

  it("rejects unsupported package versions", () => {
    const document = copyFixture();

    document.schemaVersion = 2;

    expect(() => parseDashboardDocument(document)).toThrow(
      "$.schemaVersion: expected 1",
    );
  });

  it("rejects a binding to a missing widget", () => {
    const document = copyFixture();

    document.bindings[0].target.widgetId = "missing";

    expect(() => parseDashboardDocument(document)).toThrow(
      "$.bindings[0].target.widgetId: widget does not exist",
    );
  });

  it("keeps unit codes and full uint64 IDs exact", () => {
    const document = copyFixture();

    document.variables[0].selector = {
      kind: "cyflexId",
      id: "18446744073709551615",
    };
    document.bindings[0].unitCode = -2147483648;

    expect(parseDashboardDocument(document).variables[0].selector).toEqual({
      kind: "cyflexId",
      id: "18446744073709551615",
    });

    document.variables[0].selector.id = "18446744073709551616";
    expect(() => parseDashboardDocument(document)).toThrow(
      "expected a decimal uint64 string",
    );
  });

  it("rejects session and connection secrets in exported content", () => {
    const document = copyFixture();

    document.layout.dsl.children[0].natsCredentials = "secret";

    expect(() => parseDashboardDocument(document)).toThrow(
      DashboardDocumentValidationError,
    );
    expect(() => parseDashboardDocument(document)).toThrow(
      "run session and connection data must stay outside documents",
    );
  });

  it("rejects Appsmith event handlers in new dashboard documents", () => {
    const document = copyFixture();

    document.layout.dsl.children[0].dynamicTriggerPathList = [
      { key: "onClick" },
    ];

    expect(() => parseDashboardDocument(document)).toThrow(
      "$.layout.dsl.children[0].dynamicTriggerPathList: Appsmith event handlers are unavailable",
    );
    expect(() => serializeDashboardDocument(document)).toThrow(
      DashboardDocumentValidationError,
    );
  });

  it("rejects event code even when imported JSON omits trigger metadata", () => {
    const document = copyFixture();

    document.layout.dsl.children[0].menuItems = [
      { label: "Run query", onClick: "{{GetReadings.run()}}" },
    ];

    expect(() => parseDashboardDocument(document)).toThrow(
      "$.layout.dsl.children[0].menuItems[0].onClick: Appsmith event handlers are unavailable",
    );
  });

  it("keeps ordinary display expressions available", () => {
    const document = copyFixture();

    document.layout.dsl.children[0].text = "{{EngineSpeedValue.text}}";
    document.layout.dsl.children[0].dynamicBindingPathList = [{ key: "text" }];
    document.layout.dsl.children[0].onClick = "";

    expect(parseDashboardDocument(document)).toBe(document);
  });

  it("round-trips fractional bounds generated by an Appsmith child canvas", () => {
    const document = copyFixture();
    const childCanvas = document.layout.dsl.children[1].children[0];

    childCanvas.topRow = 0.5;
    childCanvas.bottomRow = 22.5;
    childCanvas.leftColumn = 0.25;
    childCanvas.rightColumn = 561.375;

    expect(parseDashboardDocument(document)).toBe(document);
    expect(
      importDashboardDocumentJson(serializeDashboardDocument(document)),
    ).toEqual(document);
  });

  it("rejects nonfinite widget bounds", () => {
    const document = copyFixture();

    document.layout.dsl.children[1].children[0].rightColumn = Number.NaN;
    expect(() => parseDashboardDocument(document)).toThrow(
      "$.layout.dsl.children[1].children[0].rightColumn: must be JSON compatible",
    );

    document.layout.dsl.children[1].children[0].rightColumn = Infinity;
    expect(() => parseDashboardDocument(document)).toThrow(
      "$.layout.dsl.children[1].children[0].rightColumn: must be JSON compatible",
    );
  });

  it("checks that a pinned component actually has a copied group", () => {
    const document = copyFixture();

    document.componentDependencies[0].rootWidgetId = "engine-title";

    expect(() => parseDashboardDocument(document)).toThrow(
      "component must refer to a group widget in the layout",
    );
  });

  it("round-trips additional Appsmith theme properties", () => {
    const document = copyFixture();

    document.theme.properties.colors.accentColor = "#ffc857";
    document.theme.properties.fontFamily.codeFont = "Monaco";

    expect(
      importDashboardDocumentJson(serializeDashboardDocument(document)),
    ).toEqual(document);
  });

  it("requires numeric values for chart history", () => {
    const document = copyFixture();

    document.variables[0].valueType = "string";
    delete document.bindings[0].presentation.decimalPlaces;

    expect(() => parseDashboardDocument(document)).toThrow(
      "history binding requires a numeric variable",
    );
  });
});
